# Install this clone's git hooks. Idempotent; only touches this repository's
# hooks directory, never the global config. prek refuses to install when
# core.hooksPath is set, so that case warns and stops without changing it.
#
# prek runs pre-commit and pre-push. The agent identity hooks (prepare-commit-msg,
# commit-msg, post-commit) are plain shims instead: prek stashes unstaged changes
# around every stage and fails a hook whenever the work tree changes while it
# runs, so a concurrent agent's edit during a commit would fail the commit or be
# reverted.
#
# When the prek config also has hooks for one of those stages (a commit message
# linter, say), prek's own shim for that stage is installed as <hook>.prek and
# the plain hook runs it after the identity step. Both always run, and either
# failing fails the commit. The tradeoff: in a repository with such hooks, that
# stage gets prek's stash and modified-files check back, with the concurrency
# risk above. Without them, the chain costs one file test per commit.
set -euo pipefail

hooks_path=$(git config --get core.hooksPath || true)
if [[ -n $hooks_path ]]; then
  echo "install.sh: warning: core.hooksPath is $hooks_path; not installing prek hooks" >&2
  exit 0
fi

if command -v prek >/dev/null 2>&1; then
  prek=(prek)
elif command -v mise >/dev/null 2>&1; then
  prek=(mise exec -- prek)
else
  echo "install.sh: error: prek not found; run it through 'uv run' (prek is in the uv dev group)" >&2
  exit 1
fi

"${prek[@]}" install --hook-type pre-commit --hook-type pre-push

# The module needs Python 3.15, and the python3 on PATH may be older, so it
# runs through uv. Git runs hooks from the top of the work tree.
marker="# ascm interim agent identity hook (tools/interim/install.sh)"
hooks=$(git rev-parse --path-format=absolute --git-path hooks)
mkdir -p "$hooks"
for pair in prepare-commit-msg:trailer commit-msg:check post-commit:consume; do
  type=${pair%%:*}
  hook="$hooks/$type"
  # Replace a shim prek or this script wrote; keep anything else.
  if [[ -f $hook && $(<"$hook") != *"$marker"* && $(<"$hook") != *"File generated by prek"* ]]; then
    echo "install.sh: warning: $hook is not ours; leaving it" >&2
    continue
  fi
  rm -f "$hook" "$hook.prek"
  # No config (or an unreadable one) counts as no hooks for the stage.
  staged_hooks=$("${prek[@]}" list --hook-stage "$type" 2>/dev/null || true)
  if [[ -n $staged_hooks ]]; then
    "${prek[@]}" install --hook-type "$type"
    mv "$hook" "$hook.prek"
  fi
  cat >"$hook" <<SHIM
#!/bin/sh
$marker
uv run --no-project --quiet --python ">=3.15" python tools/interim/agent_identity.py ${pair#*:} "\$@"
status=\$?
next="\$(dirname "\$0")/$type.prek"
if [ -x "\$next" ]; then
  "\$next" "\$@" || status=\$?
fi
exit \$status
SHIM
  chmod +x "$hook"
done
echo "install.sh: installed git hooks"
